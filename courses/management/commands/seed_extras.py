# REBALANÇO — células do quiz com menos de 30 questões
# (idempotente por título; em produção as trilhas já existem do seed_data)
# --------------------------------------------------------------------------- #
def _seed_rebalanco(nome, desc, faixa, nivel, ordem, icone, items, xp):
    t = _mk_trilha(nome, desc, faixa, nivel, ordem, icone)
    inicio = LicaoBiblica.objects.filter(trilha=t).count() + 1
    for i, item in enumerate(items, inicio):
        titulo, texto, ref, obj, resumo, exs = item
        _add_licao(t, i, titulo, texto, ref, obj, resumo, exs, xp)
    return t


