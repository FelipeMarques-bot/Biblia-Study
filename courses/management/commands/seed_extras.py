def _mk_ouro(trilha, titulo, desc, faixa, nivel, xp, exs, peso=4):
    so, _ = SerieOuroDesafio.objects.get_or_create(
        titulo=titulo,
        defaults=dict(trilha=trilha, descricao=desc, faixa_etaria=faixa,
                      nivel=nivel, xp_recompensa=xp, ativo=True, ordem=99),
    )
    for j, e in enumerate(exs, 1):
        SerieOuroExercicio.objects.get_or_create(
            desafio_ouro=so, enunciado=e[1],
            defaults=dict(tipo=e[0], dados=e[2], peso_dificuldade=peso),
        )
    return so


