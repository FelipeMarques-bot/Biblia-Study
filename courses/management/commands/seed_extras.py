# --------------------------------------------------------------------------- #
# Helpers (mesmo padrão do seed_v2, mas sempre idempotente por nome/título/enunciado)
# --------------------------------------------------------------------------- #
def _mk_trilha(nome, desc, faixa, nivel, ordem, icone='📖'):
    t, _ = Trilha.objects.get_or_create(
        nome=nome,
        defaults=dict(descricao=desc, faixa_etaria=faixa, nivel=nivel,
                      ordem=ordem, icone=icone, ativo=True),
    )
    mudou = False
    for campo, valor in (('faixa_etaria', faixa), ('nivel', nivel), ('icone', icone)):
        if getattr(t, campo) != valor:
            setattr(t, campo, valor)
            mudou = True
    if mudou:
        t.save(update_fields=['faixa_etaria', 'nivel', 'icone'])
    return t


def _mk_licao(trilha, titulo, texto, ref, obj, resumo, ordem, xp=70):
    l, _ = LicaoBiblica.objects.get_or_create(
        trilha=trilha, titulo=titulo,
        defaults=dict(descricao=obj, texto_base=texto, referencia=ref,
                      objetivo=obj, resumo=resumo, ordem=ordem, xp_recompensa=xp),
    )
    return l


def mc(enun, alts, cor, dica='', peso=PESO):
    return ('MULTIPLA_ESCOLHA', enun, dict(alternativas=alts, indice_correto=cor, dica=dica), peso)


def vf(enun, res, dica='', peso=PESO):
    return ('VF', enun, dict(afirmativa=enun, alternativas=['Falso', 'Verdadeiro'],
                             indice_correto=1 if res else 0, dica=dica), peso)


def _add_licao(trilha, i, titulo, texto, ref, obj, resumo, exs, xp=70):
    l = _mk_licao(trilha, titulo, texto, ref, obj, resumo, i, xp)
    for j, e in enumerate(exs, 1):
        Exercicio.objects.get_or_create(
            licao=l, enunciado=e[1],
            defaults=dict(tipo=e[0], dados=e[2], ordem=j,
                          peso_dificuldade=e[3] if len(e) > 3 else PESO),
        )
    return l


